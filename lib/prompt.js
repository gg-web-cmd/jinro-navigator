/* ─────────────────────── 사용자 메시지 ─────────────────────── */

const pct = (n) => `${n}%`;

/** 학교급별 만점표. DISC 는 5점 척도, MI·RIASEC 은 4점 척도, MBTI 는 A/B 양자택일. */
function maxima(lv) {
  const per = lv?.perScale;
  if (!Number.isFinite(per)) return null;
  return {
    per,
    disc: per * 5, // 유형당 per문항 × 5점
    mi: per * 4, // 지능당 per문항 × 4점
    riasec: per * 4, // 유형당 per문항 × 4점
    mbtiAxis: per, // 지표당 per문항, A/B 중 택1
  };
}

/** "12점 / 15점 만점 / 80%" 형태로 적는다. 만점을 모르면 점수와 퍼센트만 적는다. */
function score(v, max, percent) {
  const parts = [`${v}점`];
  if (max) parts.push(`${max}점 만점`);
  parts.push(pct(percent));
  return parts.join(' / ');
}

function discBlock(r, m) {
  if (!r) return '- (결과 없음)';
  const order = r.ranked
    .map((k, i) => `  ${i + 1}순위 ${r.info?.[k]?.name ?? k} ${score(r.scores[k], m?.disc, r.percents[k])}`)
    .join('\n');
  const head = m
    ? `- 유형별 점수 (유형당 ${m.per}문항, 5점 척도, ${m.per}~${m.disc}점):`
    : '- 유형별 점수:';
  return [
    `- 1순위 유형: ${r.primaryInfo?.name ?? r.primary} — ${r.primaryInfo?.title ?? ''}`,
    `- 2순위 유형: ${r.secondaryInfo?.name ?? r.secondary} — ${r.secondaryInfo?.title ?? ''}`,
    head,
    order,
  ].join('\n');
}

function mbtiBlock(r, m) {
  if (!r) return '- (결과 없음)';
  const axes = r.axes
    .map((a) => {
      const p = pct(a.pick === a.left ? a.leftPct : a.rightPct);
      const of = m ? ` / ${m.mbtiAxis}문항 중` : '';
      return `  ${a.left}(${a.leftScore}) vs ${a.right}(${a.rightScore})${of} → ${a.pick} (${p})`;
    })
    .join('\n');
  const head = m
    ? `- 지표별 점수 (지표당 ${m.mbtiAxis}문항, A/B 양자택일):`
    : '- 지표별 점수:';
  return [`- MBTI 유형: ${r.type} (${r.info?.nickname ?? ''})`, head, axes].join('\n');
}

function miBlock(r, m) {
  if (!r) return '- (결과 없음)';
  const all = r.ranked
    .map((k, i) => `  ${i + 1}위 ${r.info?.[k]?.name ?? k}지능 ${score(r.scores[k], m?.mi, r.percents[k])}`)
    .join('\n');
  const top = r.top3.map((t, i) => `  강점 ${i + 1}위: ${t.name}지능 (${pct(t.percent)})`).join('\n');
  const bot = r.bottom3.map((t, i) => `  성장기회 ${i + 1}순위: ${t.name}지능 (${pct(t.percent)})`).join('\n');
  const head = m
    ? `- 8개 지능 전체 순위 (지능당 ${m.per}문항, 4점 척도, ${m.per}~${m.mi}점):`
    : '- 8개 지능 전체 순위:';
  return [head, all, `- 강점 지능 TOP 3:`, top, `- 상대적으로 낮은 지능 TOP 3 (성장 기회):`, bot].join('\n');
}

function riasecBlock(r, m) {
  if (!r) return '- (결과 없음)';
  const all = r.ranked
    .map((k, i) => `  ${i + 1}위 ${k}(${r.info?.[k]?.name ?? ''}) ${score(r.scores[k], m?.riasec, r.percents[k])}`)
    .join('\n');
  const head = m
    ? `- 유형별 점수 (유형당 ${m.per}문항, 4점 척도, ${m.per}~${m.riasec}점):`
    : '- 유형별 점수:';
  return [
    `- 홀랜드 코드: ${r.code}`,
    `- 1순위: ${r.primary} (${r.primaryInfo?.name ?? ''} · ${r.primaryInfo?.nickname ?? ''})`,
    `- 2순위: ${r.secondary} (${r.secondaryInfo?.name ?? ''} · ${r.secondaryInfo?.nickname ?? ''})`,
    head,
    all,
  ].join('\n');
}

/**
 * 채점 결과를 LLM에 넘길 사용자 메시지로 변환한다.
 * @param {{level?:string, student:{name?:string,school?:string,grade?:string}, results:object}} payload
 */
export function buildUserMessage(payload) {
  const s = payload.student || {};
  const r = payload.results || {};
  const lv = getLevel(payload.level);
  const m = maxima(lv);
  const who = [s.school, s.grade].filter(Boolean).join(' ');

  return `아래는 한 ${lv.label}이 자기 학교급에 맞는 문항 세트로 4가지 검사를 모두 마친 결과입니다. 이 학생을 위한 '진로 잠재력 종합 보고서'를 작성해 주세요.

## 학생 정보
- 이름: ${s.name || '학생'}
- 학교급: ${lv.label} (${lv.grades})
- 소속/학년: ${who || lv.label}
- 진로발달단계: ${lv.stage} — ${lv.stageDesc}
- 이 학교급의 문항 수: 총 ${lv.total}문항 (DISC ${lv.counts.disc} · MBTI ${lv.counts.mbti} · 다중지능 ${lv.counts.mi} · RIASEC ${lv.counts.riasec})

## 1) DISC 행동유형 검사 결과
${discBlock(r.disc, m)}

## 2) MBTI 성격유형 검사 결과
${mbtiBlock(r.mbti, m)}

## 3) 다중지능(MI) 검사 결과
${miBlock(r.mi, m)}

## 4) RIASEC 직업흥미 검사 결과
${riasecBlock(r.riasec, m)}

위 4가지 결과를 모두 반영하여, 지정된 보고서 구조와 ${lv.label} 맞춤 지침에 맞게 마크다운 보고서를 작성해 주세요.`;
}
