/* ------------------------------------------------------------------
 * 5. 도우미 — 상위 2개 지능 키로 조합 해설 찾기
 * ------------------------------------------------------------------ */

/** 두 지능 키를 알파벳 오름차순 "X-Y" 형태로 정규화한다. */
export function comboKey(k1, k2) {
  return [k1, k2].sort().join('-');
}

/** 학교급(easy 여부)에 맞는 조합 해설을 돌려준다. 없으면 default. */
export function getCombo(k1, k2, easy = false) {
  const table = easy ? MI_COMBOS_EASY : MI_COMBOS;
  return table[comboKey(k1, k2)] || table.default;
}

/** 학교급(easy 여부)에 맞는 지능 정보를 돌려준다. */
export function getMiType(key, easy = false) {
  const table = easy ? MI_TYPES_EASY : MI_TYPES;
  return table[key] || MI_TYPES[key];
}
